-- 1. สร้างตารางหมวดหมู่/สินค้า (products)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL DEFAULT 0,
    image TEXT NOT NULL,
    description TEXT,
    rating NUMERIC(2, 1) DEFAULT 5.0,
    is_best BOOLEAN DEFAULT false,
    stock INTEGER DEFAULT 100,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. สร้างตารางคำสั่งซื้อ (orders)
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    customer_email TEXT,
    customer_address TEXT NOT NULL,
    province TEXT,
    postal_code TEXT,
    items JSONB NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0,
    shipping_fee NUMERIC(10, 2) NOT NULL DEFAULT 40,
    discount NUMERIC(10, 2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
    payment_method TEXT NOT NULL DEFAULT 'transfer', -- 'transfer', 'promptpay', 'cod'
    payment_status TEXT NOT NULL DEFAULT 'pending', -- 'pending', 'paid', 'verified'
    order_status TEXT NOT NULL DEFAULT 'pending', -- 'pending', 'confirmed', 'baking', 'delivering', 'completed', 'cancelled'
    slip_url TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. สร้างตารางข้อความติดต่อ (contacts)
CREATE TABLE IF NOT EXISTS public.contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    message TEXT NOT NULL,
    status TEXT DEFAULT 'unread', -- 'unread', 'read', 'replied'
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 4. สร้างตารางคูปองส่วนลด (coupons)
CREATE TABLE IF NOT EXISTS public.coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    discount_type TEXT NOT NULL DEFAULT 'percent', -- 'percent', 'fixed'
    discount_value NUMERIC(10, 2) NOT NULL DEFAULT 0,
    min_spend NUMERIC(10, 2) DEFAULT 0,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ========================================================================
-- Row Level Security (RLS) & Policies
-- ========================================================================
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coupons ENABLE ROW LEVEL SECURITY;

-- นโยบายสำหรับ products (ทุกคนอ่านได้, แก้ไขได้เมื่อล็อกอินหรือ anon ผ่าน API)
DROP POLICY IF EXISTS "Public can view active products" ON public.products;
CREATE POLICY "Public can view active products" ON public.products
    FOR SELECT USING (is_active = true);

DROP POLICY IF EXISTS "Allow all for authenticated/anon on products" ON public.products;
CREATE POLICY "Allow all for authenticated/anon on products" ON public.products
    FOR ALL USING (true) WITH CHECK (true);

-- นโยบายสำหรับ orders (ทุกคนสร้างคำสั่งซื้อได้, อ่านคำสั่งซื้อได้เพื่อเช็คสถานะ, แอดมินแก้ไขได้)
DROP POLICY IF EXISTS "Anyone can insert orders" ON public.orders;
CREATE POLICY "Anyone can insert orders" ON public.orders
    FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Anyone can read orders" ON public.orders;
CREATE POLICY "Anyone can read orders" ON public.orders
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Anyone can update orders" ON public.orders;
CREATE POLICY "Anyone can update orders" ON public.orders
    FOR UPDATE USING (true) WITH CHECK (true);

-- นโยบายสำหรับ contacts (ทุกคนส่งข้อความได้, อ่านได้)
DROP POLICY IF EXISTS "Anyone can insert contact message" ON public.contacts;
CREATE POLICY "Anyone can insert contact message" ON public.contacts
    FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Anyone can read contacts" ON public.contacts;
CREATE POLICY "Anyone can read contacts" ON public.contacts
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Anyone can update contacts" ON public.contacts;
CREATE POLICY "Anyone can update contacts" ON public.contacts
    FOR UPDATE USING (true) WITH CHECK (true);

-- นโยบายสำหรับ coupons (ทุกคนอ่านคูปองที่เปิดใช้งานได้)
DROP POLICY IF EXISTS "Anyone can read active coupons" ON public.coupons;
CREATE POLICY "Anyone can read active coupons" ON public.coupons
    FOR SELECT USING (is_active = true);

-- ให้สิทธิ์ anon และ authenticated เข้าถึง
GRANT ALL ON TABLE public.products TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.orders TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.contacts TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.coupons TO anon, authenticated, service_role;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

